'use strict';

/**
 * Emits the Code-node source for the brand card renderer webhook.
 *
 * The card page has to be served as real text/html for a screenshot service to
 * render it, and GitHub's file CDNs will not do that, so n8n serves it itself.
 *
 * Fonts are referenced from the repo rather than embedded, pinned to a commit.
 * Embedding all five faces makes the page 1.6 MB, which is too much to carry in
 * a workflow node; by URL it is a few kB.
 *
 *   node render/build-brand-webhook.js [sha] > out.js
 */

const { execSync } = require('child_process');
const { buildBrandShell } = require('./brand-template');

const sha = process.argv[2] || execSync('git rev-parse HEAD', { cwd: __dirname }).toString().trim();
const fontBase = 'https://raw.githubusercontent.com/Malek-Abdelrahman918/LinkedIn-/' + sha + '/render/fonts';

const html = buildBrandShell({ fontBase });

process.stdout.write(
  '// The brand card page, served as HTML. Generated by render/build-brand-webhook.js\n' +
  '// from render/brand-template.js and render/brand.js. Edit there and regenerate;\n' +
  '// do not hand-edit this node.\n' +
  '// Fonts pinned to ' + sha + '\n' +
  'const html = ' + JSON.stringify(html) + ';\n\n' +
  'return [{ json: { html: html } }];\n'
);
